"""Generate the Flyway seed migration from the master JSON.

ironoak_seed.json is the source of truth. Re-run this script after editing it:

    python scripts/make_seed.py

The generated V2 file must never be edited by hand.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED_JSON = ROOT / "ironoak_seed.json"
LABELS_JSON = ROOT / "ml" / "idx_to_class.json"
OUT_SQL = ROOT / "src" / "main" / "resources" / "db" / "migration" / "V2__seed_catalog.sql"

PRODUCT_FIELDS = [
    "sku", "name", "brand", "category", "description",
    "price", "stock_quantity", "warranty_months", "image_url", "is_active",
]
MACHINE_FIELDS = [
    "model_code", "name", "description", "power_kw", "spindle_min_rpm",
    "spindle_max_rpm", "table_length_mm", "table_width_mm", "price",
    "warranty_months", "image_url", "is_active",
]
SERVICE_FIELDS = [
    "code", "name", "description", "pricing_type", "fixed_price", "hourly_rate",
    "estimated_min_hours", "estimated_max_hours", "price_unit", "is_active",
]


def lit(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "ARRAY[" + ", ".join(lit(v) for v in value) + "]::text[]"
    return "'" + str(value).replace("'", "''") + "'"


def validate(seed):
    labels = json.loads(LABELS_JSON.read_text(encoding="utf-8"))
    classes = set(labels.values()) if isinstance(labels, dict) else set(labels)
    catalog = seed["tool_catalog"]
    errors = []
    if set(catalog) != classes:
        errors.append(f"seed/model mismatch: only in seed {sorted(set(catalog) - classes)}, "
                      f"only in model {sorted(classes - set(catalog))}")
    skus = set()
    for key, entry in catalog.items():
        if entry["tool_category"]["model_label"] != key:
            errors.append(f"{key}: model_label differs from key")
        for product in entry["products"]:
            if product["sku"] in skus:
                errors.append(f"duplicate sku {product['sku']}")
            skus.add(product["sku"])
    if errors:
        sys.exit("seed validation failed:\n  " + "\n  ".join(errors))


def build(seed):
    out = ["-- GENERATED by scripts/make_seed.py from ironoak_seed.json. Do not edit by hand.", ""]

    out.append("-- tool_category")
    for entry in seed["tool_catalog"].values():
        c = entry["tool_category"]
        out.append(
            "INSERT INTO tool_category (model_label, display_name, synonyms, description) VALUES "
            f"({lit(c['model_label'])}, {lit(c['display_name'])}, {lit(c['synonyms'])}, {lit(c['description'])});"
        )

    out += ["", "-- product"]
    columns = "tool_category_id, vision_name, " + ", ".join(PRODUCT_FIELDS)
    for key, entry in seed["tool_catalog"].items():
        for p in entry["products"]:
            values = ", ".join(lit(p[f]) for f in PRODUCT_FIELDS)
            out.append(
                f"INSERT INTO product ({columns}) "
                f"SELECT id, model_label, {values} FROM tool_category WHERE model_label = {lit(key)};"
            )

    out += ["", "-- milling_machine"]
    for m in seed["milling_machines"]:
        out.append(
            f"INSERT INTO milling_machine ({', '.join(MACHINE_FIELDS)}) VALUES "
            f"({', '.join(lit(m[f]) for f in MACHINE_FIELDS)});"
        )

    out += ["", "-- service_offering_category"]
    categories = list(dict.fromkeys(s["category"] for s in seed["service_offerings"]))
    for name in categories:
        out.append(f"INSERT INTO service_offering_category (name) VALUES ({lit(name)});")

    out += ["", "-- service_offering"]
    columns = "service_offering_category_id, " + ", ".join(SERVICE_FIELDS)
    for s in seed["service_offerings"]:
        values = ", ".join(lit(s[f]) for f in SERVICE_FIELDS)
        out.append(
            f"INSERT INTO service_offering ({columns}) "
            f"SELECT id, {values} FROM service_offering_category WHERE name = {lit(s['category'])};"
        )

    return "\n".join(out) + "\n"


def main():
    seed = json.loads(SEED_JSON.read_text(encoding="utf-8"))
    validate(seed)
    OUT_SQL.write_text(build(seed), encoding="utf-8")
    products = sum(len(e["products"]) for e in seed["tool_catalog"].values())
    print(f"wrote {OUT_SQL.relative_to(ROOT)}: {len(seed['tool_catalog'])} categories, {products} products, "
          f"{len(seed['milling_machines'])} machines, {len(seed['service_offerings'])} services")


if __name__ == "__main__":
    main()
