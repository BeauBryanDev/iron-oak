package com.ironoak.services;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Advanced object-oriented engineering class for kinematic, dynamic,
 * power validation, and tool life estimation in CNC milling machines.
 */
public class CNCalculator {

    // Physical, geometric, and wear parameters
    private double cuttingSpeed; // vc
    private double diameter; // diametro
    private double feedPerTooth; // fz
    private int numberOfTeeth; // num_dientes
    private double depthOfCut; // ap
    private double widthOfCut; // ae
    private double kc1; // kc1
    private double mc; // mc
    private double maxMotorPowerKw; // potencia_max_motor_kw
    private double machineEfficiency; // eficiencia_maquina
    private double helixAngleDegrees; // angulo_helice_grados
    private double taylorC; // taylor_c
    private double taylorN; // taylor_n

    /**
     * Initializes all physical, geometric, and wear parameters.
     */
    public CNCalculator(
            double cuttingSpeed,
            double diameter,
            double feedPerTooth,
            int numberOfTeeth,
            double depthOfCut,
            double widthOfCut,
            double kc1,
            double mc,
            double maxMotorPowerKw,
            double machineEfficiency,
            double helixAngleDegrees,
            double taylorC,
            double taylorN) {

        this.cuttingSpeed = cuttingSpeed;
        this.diameter = diameter;
        this.feedPerTooth = feedPerTooth;
        this.numberOfTeeth = numberOfTeeth;
        this.depthOfCut = depthOfCut;
        this.widthOfCut = widthOfCut;
        this.kc1 = kc1;
        this.mc = mc;
        this.maxMotorPowerKw = maxMotorPowerKw;
        this.machineEfficiency = machineEfficiency;
        this.helixAngleDegrees = helixAngleDegrees;
        this.taylorC = taylorC;
        this.taylorN = taylorN;
    }

    /**
     * Calculates the spindle speed in RPM.
     */
    public double calculateRpm() {
        return (cuttingSpeed * 1000.0) / (Math.PI * diameter);
    }

    /**
     * Calculates the feed rate in mm/min.
     */
    public double calculateFeedRate() {
        double rpm = calculateRpm();
        return feedPerTooth * numberOfTeeth * rpm;
    }

    /**
     * Calculates the Material Removal Rate (MRR) in cm^3/min.
     */
    public double calculateMrr() {
        double feedRate = calculateFeedRate();
        return (depthOfCut * widthOfCut * feedRate) / 1000.0;
    }

    /**
     * Calculates the mean chip thickness (hm) in mm.
     */
    public double calculateChipThickness() {
        return feedPerTooth * Math.sqrt(widthOfCut / diameter);
    }

    /**
     * Calculates the specific cutting force (kc) in N/mm^2.
     */
    public double calculateSpecificForce() {
        double hm = calculateChipThickness();
        return kc1 * Math.pow(hm, -mc);
    }

    /**
     * Calculates the tangential cutting force (Ft) in Newtons.
     */
    public double calculateTangentialForce() {
        double kc = calculateSpecificForce();
        double hm = calculateChipThickness();
        return kc * depthOfCut * hm;
    }

    /**
     * Calculates the axial or thrust force (Fa) in Newtons
     * generated by the milling cutter's helix angle.
     */
    public double calculateAxialForce() {
        double ft = calculateTangentialForce();
        double helixRad = Math.toRadians(helixAngleDegrees);
        return ft * Math.tan(helixRad);
    }

    /**
     * Calculates the required cutting power in kW.
     */
    public double calculatePower() {
        double kc = calculateSpecificForce();
        double feedRate = calculateFeedRate();
        double mrrMm3 = depthOfCut * widthOfCut * feedRate;
        return (kc * mrrMm3) / 60000000.0;
    }

    /**
     * Calculates the spindle torque in N*m.
     */
    public double calculateSpindleTorque() {
        double power = calculatePower();
        double rpm = calculateRpm();
        if (rpm == 0) {
            return 0.0;
        }
        return (9550.0 * power) / rpm;
    }

    /**
     * Calculates the estimated tool life (T) in minutes
     * using the modified Taylor equation.
     */
    public double calculateTaylorToolLife() {
        if (cuttingSpeed <= 0) {
            return 0.0;
        }
        // T = (C / V)^(1 / n)
        return Math.pow(taylorC / cuttingSpeed, 1.0 / taylorN);
    }

    /**
     * Checks if the required power exceeds the motor limit.
     */
    public Map<String, Object> checkMotorLimit() {
        double cuttingPower = calculatePower();
        double requiredMotorPower = cuttingPower / machineEfficiency;
        double loadPercentage = (requiredMotorPower / maxMotorPowerKw) * 100.0;
        boolean isSafe = requiredMotorPower <= maxMotorPowerKw;

        String status = isSafe
                ? "SAFE: Operation within motor range."
                : "DANGER OF MOTOR OVERLOAD!";

        Map<String, Object> result = new LinkedHashMap<>();
        result.put("Motor Status", status);
        result.put("Required Power (kW)", roundTo(requiredMotorPower, 2));
        result.put("Load Percentage (%)", roundTo(loadPercentage, 2));

        return result;
    }

    /**
     * Generates a complete map with all machining metrics.
     */
    public Map<String, Object> getEngineeringReport() {
        Map<String, Object> report = new LinkedHashMap<>();

        report.put("Spindle Speed (RPM)", roundTo(calculateRpm(), 2));
        report.put("Feed Rate (mm/min)", roundTo(calculateFeedRate(), 2));
        report.put("MRR (cm^3/min)", roundTo(calculateMrr(), 2));
        report.put("Chip Thickness hm (mm)", roundTo(calculateChipThickness(), 4));
        report.put("Tangential Force Ft (N)", roundTo(calculateTangentialForce(), 2));
        report.put("Axial Force Fa (N)", roundTo(calculateAxialForce(), 2));
        report.put("Cutting Power Pc (kW)", roundTo(calculatePower(), 2));
        report.put("Spindle Torque T (N*m)", roundTo(calculateSpindleTorque(), 2));
        report.put("Tool Life (min)", roundTo(calculateTaylorToolLife(), 2));

        report.putAll(checkMotorLimit());

        return report;
    }

    /**
     * Helper method to round a double value to a specified number of decimal
     * places.
     */
    private double roundTo(double value, int places) {
        double scale = Math.pow(10, places);
        return Math.round(value * scale) / scale;
    }

}
